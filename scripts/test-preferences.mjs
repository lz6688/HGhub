import assert from 'node:assert/strict';
import { join } from 'node:path';

export async function testPreferences({page,browser,dispatch,base,ui,output,report}) {
  const item={id:'same',title:'可配置封面',type:'movie'};
  const code=`export const meta={id:'fixture.preferences',name:'偏好测试源',version:'1.0.0',protocol:1,allowInsecureHttp:true,defaultHeaders:{'X-Fixture-Token':'local-fixture'}};export default()=>{
    const items=Array.from({length:12},(_,i)=>({id:'item-'+i,title:'测试作品 '+i,type:'movie',cover:${JSON.stringify(base)}+'/cover.svg'}));
    return {feed:{list(){return {items:items.slice(0,1)}}},catalog:{getCategories(){return [{id:'all',label:'全部作品'}]},list(){return {items}}},media:{getDetail({id}){return {id,title:'测试作品',playlists:[{id:'main',episodes:[{id:'episode',index:1}]}]}},resolvePlayback(){return {streams:[{url:${JSON.stringify(base)}+'/clip.mp4',format:'progressive'}]}}}};};`;
  const imported=await dispatch({action:'import',params:{code}});assert(imported.ok,JSON.stringify(imported));
  await page.reload();
  const calls=[], errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(r.url().endsWith('/__hpp_test_ipc'))calls.push(JSON.parse(r.postData()));});
  const rail=page.getByRole('navigation',{name:'主导航'});
  const settings=()=>rail.getByRole('button',{name:'设置',exact:true}).click();
  await settings();
  await page.getByLabel('启动后打开',{exact:true}).selectOption('category');
  await page.getByLabel('每行卡片数',{exact:true}).selectOption('5');
  await page.getByRole('button',{name:'首页自动播放',exact:true}).click();
  await page.getByRole('button',{name:/首页播放片源/}).click();
  await page.getByRole('button',{name:'全选',exact:true}).click();
  await page.getByRole('button',{name:'保存选择',exact:true}).click();
  await page.screenshot({path:join(output,'preferences-settings.png')});
  await page.getByRole('button',{name:'首页自动播放',exact:true}).click();
  calls.length=0;
  await page.reload();
  await page.locator('.hpp-category-page .legacy-row-card').first().waitFor();
  assert.equal(await page.locator('video').count(),0);
  assert(!calls.some(c=>c.params?.method==='feed.list'||c.action==='media.prepare'), 'non-home startup does not request homepage media');
  await settings();await page.getByRole('button',{name:'首页自动播放',exact:true}).click();
  await rail.getByRole('button',{name:'分类',exact:true}).click();
  await page.locator('.legacy-row-card').first().waitFor();
  const rowWidth=await page.locator('.legacy-row-card').first().evaluate(el=>el.getBoundingClientRect().width);
  const containerWidth=await page.locator('.hpp-preview-strip').first().evaluate(el=>el.getBoundingClientRect().width);
  assert(Math.abs(rowWidth-(containerWidth-56)/5)<1);
  await page.locator('button.legacy-category-heading').first().click();
  await page.locator('.hpp-cards .hpp-poster img').first().waitFor();
  const grid=await page.locator('.hpp-cards').evaluate(el=>({columns:getComputedStyle(el).gridTemplateColumns.split(' ').length,width:el.getBoundingClientRect().width,card:el.firstElementChild.getBoundingClientRect().width,poster:el.querySelector('.hpp-poster').getBoundingClientRect().width}));
  assert.equal(grid.columns,5);assert(Math.abs(grid.card-grid.poster)<1);assert(Math.abs(grid.card-(grid.width-56)/5)<1);
  await page.screenshot({path:join(output,'preferences-grid.png')});
  await page.setViewportSize({width:3840,height:1400});
  assert((await page.locator('.hpp-cards .hpp-media-card').first().boundingBox()).width<=220.1);
  await page.setViewportSize({width:1180,height:820});
  await rail.getByRole('button',{name:'首页',exact:true}).click();
  await page.getByRole('button',{name:'开始首页播放',exact:true}).waitFor();
  assert(!calls.some(c=>c.params?.method==='feed.list'||c.action==='media.prepare'));
  await page.getByRole('button',{name:'开始首页播放',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('video')?.currentTime>.1);
  assert(calls.some(c=>c.params?.method==='feed.list'));
  await settings();
  await page.getByRole('button',{name:/首页播放片源/}).click();
  await page.getByRole('button',{name:'清空选择',exact:true}).click();
  await page.getByRole('button',{name:'保存选择',exact:true}).click();
  await page.getByRole('button',{name:'首页自动播放',exact:true}).click();
  await page.getByLabel('启动后打开',{exact:true}).selectOption('home');
  calls.length=0;await page.reload();
  await page.getByRole('button',{name:'选择片源',exact:true}).waitFor();
  assert.equal(await page.locator('video').count(),0);
  assert(!calls.some(c=>c.params?.method==='feed.list'||c.action==='media.prepare'));
  assert.deepEqual(await page.evaluate(()=>JSON.parse(localStorage.getItem('hpp.preferences')).homeIds),[]);
  for(const pluginId of ['fixture.preferences','fixture.other']) {
    assert((await dispatch({action:'library.put',params:{pluginId,item,favorite:true,tracking:true}})).ok);
    assert((await dispatch({action:'library.progress.set',params:{pluginId,mediaId:item.id,episodeId:'episode',positionSec:12}})).ok);
  }
  await page.reload();await rail.locator('.win-account').click();
  await page.getByRole('button',{name:/^历史/}).click();
  await page.getByRole('button',{name:'选择历史',exact:true}).click();
  const selected=page.locator('.library-history .hpp-local-entry').filter({hasText:'偏好测试源'}).filter({hasText:'可配置封面'});
  await selected.getByRole('checkbox').check();
  await page.screenshot({path:join(output,'preferences-history.png')});
  page.once('dialog',d=>d.accept());await page.getByRole('button',{name:'删除所选 (1)',exact:true}).click();
  await selected.waitFor({state:'detached'});
  const a=(await dispatch({action:'library.get',params:{pluginId:'fixture.preferences',mediaId:'same'}})).value;
  const b=(await dispatch({action:'library.get',params:{pluginId:'fixture.other',mediaId:'same'}})).value;
  assert(!a.lastProgress);assert(a.favorite&&a.tracking);assert(b.lastProgress);assert(b.favorite&&b.tracking);
  await settings();await page.getByLabel('启动后打开',{exact:true}).selectOption('profile');await page.reload();await page.locator('.hpp-library-page').waitFor();
  await settings();await page.getByLabel('启动后打开',{exact:true}).selectOption('search');await page.reload();await page.getByRole('textbox',{name:'搜索所有插件'}).waitFor();
  const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,userAgent:'Mozilla/5.0 (Linux; Android 12) AppleWebKit/537.36 Chrome/130.0.0.0 Mobile Safari/537.36'});
  const mobile=await context.newPage();mobile.on('pageerror',e=>errors.push(e.message));
  await mobile.route('**/__hpp_test_ipc',async route=>route.fulfill({contentType:'application/json',body:JSON.stringify(await dispatch(JSON.parse(route.request().postData())))}));
  await mobile.addInitScript(()=>{localStorage.setItem('hpp.startPage','"category"');localStorage.setItem('hpp.cardColumns','4')});
  await mobile.goto(ui+'tests/plugins.html');await mobile.locator('.legacy-row-card').first().waitFor();
  const mobileSizes=await mobile.locator('.hpp-preview-strip').first().evaluate(el=>({width:el.clientWidth,card:el.firstElementChild.getBoundingClientRect().width}));
  assert(Math.abs(mobileSizes.card-(mobileSizes.width-42)/4)<1);
  await mobile.screenshot({path:join(output,'preferences-mobile.png')});
  await mobile.locator('.hg-tabbar').getByRole('button',{name:'我的',exact:true}).click();
  await mobile.getByRole('button',{name:'历史',exact:true}).click();
  await mobile.getByRole('button',{name:'选择历史',exact:true}).click();
  await mobile.getByRole('checkbox').first().check();
  await mobile.screenshot({path:join(output,'preferences-mobile-history.png')});await context.close();
  assert.deepEqual(errors,[]);
  report.passed.push('Preferences: persisted startup destinations, gated homepage autoplay, empty source selection, 4/5-column desktop/mobile layouts and width cap, selected history deletion preserving favorites and other sources');
}
